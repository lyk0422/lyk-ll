-- 冷链运输追溯表结构（H2 内存库，MODE=MySQL；数据仅保留在 JVM 生命周期内）
CREATE TABLE IF NOT EXISTS shipment (
    shipment_id                  VARCHAR(64)  NOT NULL PRIMARY KEY,
    min_temp_c                   DECIMAL(8,3) NOT NULL,
    max_temp_c                   DECIMAL(8,3) NOT NULL,
    max_excursion_minutes        INT          NOT NULL,
    max_sample_interval_minutes  INT          NOT NULL,
    version                      INT          NOT NULL,
    created_at                   BIGINT       NOT NULL
);

CREATE TABLE IF NOT EXISTS custody_segment (
    id              BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id     VARCHAR(64)  NOT NULL,
    version         INT          NOT NULL,
    custodian       VARCHAR(128) NOT NULL,
    start_time      BIGINT       NOT NULL,
    end_time        BIGINT,
    first_sequence  BIGINT,
    last_sequence   BIGINT,
    status          VARCHAR(16)  NOT NULL,
    CONSTRAINT uq_segment_shipment_version UNIQUE (shipment_id, version)
);
CREATE INDEX IF NOT EXISTS idx_segment_shipment ON custody_segment (shipment_id);

CREATE TABLE IF NOT EXISTS temperature_reading (
    shipment_id    VARCHAR(64)  NOT NULL,
    sequence_no    BIGINT       NOT NULL,
    sampled_at     BIGINT       NOT NULL,
    temperature_c  DECIMAL(8,3) NOT NULL,
    created_at     BIGINT       NOT NULL,
    CONSTRAINT pk_temperature_reading PRIMARY KEY (shipment_id, sequence_no)
);

CREATE TABLE IF NOT EXISTS handover_record (
    id               BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id      VARCHAR(64)  NOT NULL,
    request_id       VARCHAR(64)  NOT NULL,
    fingerprint      CHAR(64)     NOT NULL,
    custodian        VARCHAR(128) NOT NULL,
    expected_version INT          NOT NULL,
    receiver         VARCHAR(128) NOT NULL,
    handover_at      BIGINT       NOT NULL,
    last_sequence    BIGINT       NOT NULL,
    result_status    VARCHAR(16)  NOT NULL,
    closed_version   INT          NOT NULL,
    created_at       BIGINT       NOT NULL,
    CONSTRAINT uq_handover_request UNIQUE (shipment_id, request_id)
);
CREATE INDEX IF NOT EXISTS idx_handover_shipment ON handover_record (shipment_id);

COMMENT ON COLUMN shipment.shipment_id IS '货件唯一标识';
COMMENT ON COLUMN shipment.min_temp_c IS '允许温度闭区间下限，单位摄氏度，端点等于阈值视为合格';
COMMENT ON COLUMN shipment.max_temp_c IS '允许温度闭区间上限，单位摄氏度，端点等于阈值视为合格';
COMMENT ON COLUMN shipment.max_excursion_minutes IS '最大连续超限分钟数，连续超限严格大于该值才判 EXCURSION';
COMMENT ON COLUMN shipment.max_sample_interval_minutes IS '相邻读数最大采样间隔分钟数，严格大于该值判 INCOMPLETE';
COMMENT ON COLUMN shipment.version IS '当前保管版本号，等于已完成交接次数，也是当前打开段的 version';
COMMENT ON COLUMN shipment.created_at IS '创建时间，Unix 毫秒时间戳（UTC）';

COMMENT ON COLUMN custody_segment.shipment_id IS '所属货件标识';
COMMENT ON COLUMN custody_segment.version IS '运输段序号，从 0 开始，货件内唯一';
COMMENT ON COLUMN custody_segment.custodian IS '该段保管方';
COMMENT ON COLUMN custody_segment.start_time IS '本段开始时间，Unix 毫秒时间戳（UTC）';
COMMENT ON COLUMN custody_segment.end_time IS '本段关闭（交接）时间，Unix 毫秒时间戳（UTC）；NULL 表示段仍打开';
COMMENT ON COLUMN custody_segment.first_sequence IS '本段已收最小设备序号，闭区间起点；段打开且尚无读数时为 NULL';
COMMENT ON COLUMN custody_segment.last_sequence IS '本段末设备序号；打开时为当前已收最大序号，关闭时取交接请求的 lastSequence；无读数时为 NULL';
COMMENT ON COLUMN custody_segment.status IS '段状态：OPEN/CLEAR/EXCURSION/INCOMPLETE';

COMMENT ON COLUMN temperature_reading.shipment_id IS '所属货件标识';
COMMENT ON COLUMN temperature_reading.sequence_no IS '设备序号，货件内全局严格递增，允许乱序到达';
COMMENT ON COLUMN temperature_reading.sampled_at IS '采样时间，Unix 毫秒时间戳（UTC）';
COMMENT ON COLUMN temperature_reading.temperature_c IS '采样温度，单位摄氏度，必须为有限数值';
COMMENT ON COLUMN temperature_reading.created_at IS '服务端写入时间，Unix 毫秒时间戳（UTC）';

COMMENT ON COLUMN handover_record.shipment_id IS '所属货件标识';
COMMENT ON COLUMN handover_record.request_id IS '交接请求幂等键，货件内唯一';
COMMENT ON COLUMN handover_record.fingerprint IS '请求参数指纹（SHA-256），同键异参冲突时返回 409';
COMMENT ON COLUMN handover_record.custodian IS '交出方，须与当前打开段保管方一致';
COMMENT ON COLUMN handover_record.expected_version IS '请求方预期的当前版本，与实际不符返回 409';
COMMENT ON COLUMN handover_record.receiver IS '接收方，即新段保管方';
COMMENT ON COLUMN handover_record.handover_at IS '交接时间，Unix 毫秒时间戳（UTC）';
COMMENT ON COLUMN handover_record.last_sequence IS '本次交接覆盖的最后一个设备序号';
COMMENT ON COLUMN handover_record.result_status IS '首次交接冻结的判定结果：CLEAR/EXCURSION/INCOMPLETE';
COMMENT ON COLUMN handover_record.closed_version IS '被关闭段的 version';
COMMENT ON COLUMN handover_record.created_at IS '首次处理时间，Unix 毫秒时间戳（UTC）';
