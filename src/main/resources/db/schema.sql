-- 机组值勤合规服务：H2（MODE=MySQL）自动建表脚本。
-- 所有时刻列统一以 UTC 存储，日期窗口列以 UTC 日历日为准。

CREATE TABLE airport (
    code          VARCHAR(8)  NOT NULL PRIMARY KEY,
    time_zone_id  VARCHAR(64) NOT NULL,
    display_name  VARCHAR(64) NOT NULL
);
COMMENT ON TABLE  airport            IS '机场主数据（合成数据）：决定报到时刻分档所用的本地时区';
COMMENT ON COLUMN airport.code       IS '机场三字/四字合成代码，主键';
COMMENT ON COLUMN airport.time_zone_id IS 'IANA 时区 ID，如 UTC、Asia/Shanghai';
COMMENT ON COLUMN airport.display_name IS '机场显示名称（合成）';

CREATE TABLE crew_member (
    id                 BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_code        VARCHAR(32)  NOT NULL UNIQUE,
    name               VARCHAR(64)  NOT NULL,
    base_airport_code  VARCHAR(8)
);
COMMENT ON TABLE  crew_member                    IS '机组成员主数据（合成数据）';
COMMENT ON COLUMN crew_member.member_code        IS '机组成员工号，业务唯一键';
COMMENT ON COLUMN crew_member.name               IS '机组成员姓名（合成）';
COMMENT ON COLUMN crew_member.base_airport_code  IS '常驻基地机场代码，可空';

CREATE TABLE flight (
    id                       BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_no                VARCHAR(16)  NOT NULL UNIQUE,
    departure_airport_code   VARCHAR(8)   NOT NULL,
    arrival_airport_code     VARCHAR(8)   NOT NULL
);
COMMENT ON TABLE  flight                          IS '航班主数据（合成数据），不含具体排班日期';
COMMENT ON COLUMN flight.flight_no                IS '航班号，业务唯一键';
COMMENT ON COLUMN flight.departure_airport_code   IS '起飞机场代码，报到时段按该机场本地时间分档';
COMMENT ON COLUMN flight.arrival_airport_code     IS '到达机场代码';

CREATE TABLE check_batch (
    id              BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id        VARCHAR(40)  NOT NULL UNIQUE,
    overall_result  VARCHAR(16)  NOT NULL,
    sealed          BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP    NOT NULL,
    finalized_at    TIMESTAMP    NULL
);
COMMENT ON TABLE  check_batch                 IS '排班校验批次：一次整组校验及封板的聚合根';
COMMENT ON COLUMN check_batch.batch_id        IS '对外批次号（UUID），业务唯一键';
COMMENT ON COLUMN check_batch.overall_result  IS '整组结论：LEGAL 全员合法 / ILLEGAL 至少一名成员违规';
COMMENT ON COLUMN check_batch.sealed          IS '是否已封板：TRUE 为终态，不可更改结论';
COMMENT ON COLUMN check_batch.created_at      IS '批次创建时刻（UTC）';
COMMENT ON COLUMN check_batch.finalized_at    IS '封板时刻（UTC），未封板为空';

CREATE TABLE duty_record (
    id                        BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id                  BIGINT       NOT NULL,
    request_id                VARCHAR(64)  NOT NULL UNIQUE,
    member_code               VARCHAR(32)  NOT NULL,
    flight_no                 VARCHAR(16)  NOT NULL,
    report_time_utc           TIMESTAMP    NOT NULL,
    planned_end_utc           TIMESTAMP    NOT NULL,
    tier_limit_minutes        INT          NOT NULL,
    total_extension_minutes   INT          NOT NULL DEFAULT 0,
    duty_end_utc              TIMESTAMP    NOT NULL,
    result                    VARCHAR(16)  NOT NULL,
    reasons                   VARCHAR(1000),
    accepted                  BOOLEAN      NOT NULL,
    fingerprint               VARCHAR(64)  NOT NULL,
    created_at                TIMESTAMP    NOT NULL,
    CONSTRAINT fk_duty_batch FOREIGN KEY (batch_id) REFERENCES check_batch (id)
);
COMMENT ON TABLE  duty_record                          IS '机组成员值勤记录（FDP）：一行对应一名成员在一次批次中的判定';
COMMENT ON COLUMN duty_record.request_id               IS '客户端幂等键，唯一；同键重放返回首次判定';
COMMENT ON COLUMN duty_record.member_code              IS '值勤机组成员工号';
COMMENT ON COLUMN duty_record.flight_no                IS '值勤航班号';
COMMENT ON COLUMN duty_record.report_time_utc          IS '报到时刻（UTC），FDP 起算点';
COMMENT ON COLUMN duty_record.planned_end_utc          IS '计划执勤结束时刻（UTC，不含延误延长）';
COMMENT ON COLUMN duty_record.tier_limit_minutes       IS '按报到时段分档得到的 FDP 上限（分钟）：13h/12h/10h';
COMMENT ON COLUMN duty_record.total_extension_minutes  IS '本 FDP 累计延误延长（分钟，0 表示无延长）';
COMMENT ON COLUMN duty_record.duty_end_utc             IS '实际执勤结束时刻（UTC）= 计划结束 + 累计延长';
COMMENT ON COLUMN duty_record.result                   IS '该成员判定：LEGAL 合法 / ILLEGAL 违规';
COMMENT ON COLUMN duty_record.reasons                  IS '违规原因代码 JSON 数组，合法为空数组';
COMMENT ON COLUMN duty_record.accepted                 IS '是否计入后续历史：TRUE 合法受理；FALSE 违规驳回，不占时段不计工时';
COMMENT ON COLUMN duty_record.fingerprint              IS '请求指纹（SHA-256），覆盖 requestId、成员、航班、报到时刻等全部业务参数';
COMMENT ON COLUMN duty_record.created_at               IS '记录创建时刻（UTC）';

CREATE UNIQUE INDEX ux_duty_member_flight_report
    ON duty_record (member_code, flight_no, report_time_utc);
CREATE INDEX ix_duty_member_window
    ON duty_record (member_code, report_time_utc, accepted);

CREATE TABLE delay_event (
    id                 BIGINT       NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    duty_record_id     BIGINT       NOT NULL,
    request_id         VARCHAR(64)  NOT NULL UNIQUE,
    extension_minutes  INT          NOT NULL,
    late               BOOLEAN      NOT NULL DEFAULT FALSE,
    event_day_utc      DATE         NOT NULL,
    note               VARCHAR(255),
    created_at         TIMESTAMP    NOT NULL,
    CONSTRAINT fk_delay_duty FOREIGN KEY (duty_record_id) REFERENCES duty_record (id)
);
COMMENT ON TABLE  delay_event                      IS '延误延长事件：封板后补交的事件仅留痕，不影响已封板结论';
COMMENT ON COLUMN delay_event.duty_record_id       IS '关联值勤记录主键';
COMMENT ON COLUMN delay_event.request_id           IS '延误上报幂等键，唯一';
COMMENT ON COLUMN delay_event.extension_minutes    IS '本次延长分钟数（正数）';
COMMENT ON COLUMN delay_event.late                 IS '是否封板后补交：TRUE 为迟到事件，不推翻结论';
COMMENT ON COLUMN delay_event.event_day_utc        IS '延长归属的 UTC 日历日（取 FDP 报到日），用于每日 2 小时上限';
COMMENT ON COLUMN delay_event.note                 IS '延误备注，可空';
COMMENT ON COLUMN delay_event.created_at           IS '事件创建时刻（UTC）';
