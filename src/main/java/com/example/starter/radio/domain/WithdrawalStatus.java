package com.example.starter.radio.domain;

/**
 * 未发药整批撤回单状态机（合成数据软件验证，不用于真实给药决策）：
 * PENDING 待双人批准：申请仅冻结清单，不作废任何分装；
 * PENDING → APPROVED：两名不同人员批准且最终事务重查全清单仍合法，同批分装一起转为 VOID（终态）；
 * PENDING → VOID：申请整体撤销（撤回单自身作废），释放全部任务占用；
 * 申请时任一项不合法（未知分装、核素不一致、已拒绝、已发药、已属其它活动撤回单）整单 REJECTED（终态），
 * 不先作废其他项，拒绝不留下任何部分 VOID。
 */
public enum WithdrawalStatus {

    /** 撤回申请已建立并冻结全清单，等待两名不同人员批准；期间原合法发药与候选批准仍可先行。 */
    PENDING,

    /** 双人批准通过且最终事务重查全清单合法：同批分装已一起转为分装 VOID 终态，撤回单终态。 */
    APPROVED,

    /** 未批准申请被整体撤销，撤回单终态；其占用全部释放。 */
    VOID,

    /** 申请时存在不合法项，整单拒绝，终态；不产生任何分装 VOID，不占用任务。 */
    REJECTED
}
