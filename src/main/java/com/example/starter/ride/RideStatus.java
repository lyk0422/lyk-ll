package com.example.starter.ride;

/**
 * 设备状态机：日检→试运行→开放→运行监测→闭园复检/归档；
 * 登记大修进入大修中（暂停开放），监督检验合格进入待复开。
 * 单状态字段保证“停运/大修”与“开放”互斥，形成唯一终态。
 */
public enum RideStatus {

    /** 待日检（初始状态，未日检设备无法开放） */
    PENDING_CHECK,

    /** 日检合格，可进行空载试运行 */
    CHECKED,

    /** 试运行恰3次合格，可开放载客 */
    READY,

    /** 开放载客，接受运行监测读数 */
    OPEN,

    /** 载荷或速度超阈值触发缓停，须复检合格方可复开 */
    SUSPENDED,

    /** 故障停运（安全装置失效或试运行异常），须复检合格方可复开 */
    STOPPED,

    /** 复检或大修后监督检验合格，可执行复开（受同日复开次数与年度证书门禁约束） */
    RECHECKED,

    /** 大修中：登记大修后暂停开放，旧监督检验失效，须重新监督检验合格 */
    OVERHAUL,

    /** 闭园归档，终态；迟到运行数据只记迟到事件 */
    ARCHIVED
}
